"""アプリがしゃべる全セリフの一覧（app.js の voice.say(...) と同じ文字列にすること）"""
SONGS = ["アラジン", "ねこふんじゃった", "やまのおんがくか", "こぎつね", "チューリップ", "メリーさんのひつじ", "ひげじいさん", "きらきらぼし"]
SPECIES = [("にわとり", False), ("ライオン", False), ("くじら", False), ("きょうりゅう", False), ("ちょうちょ", False), ("ドラゴン", True), ("ユニコーン", True)]
CHILDREN = ["ひよりちゃん", "みやびくん"]

def lines():
    L = []
    L += [f"{t}、ひけたね！ サイコロ、ころころ" for t in SONGS]
    L += ["いちマス すすむよ", "にマス すすむよ", "さんマス すすむよ", "いち", "に", "さん"]
    L += ["キラキラ ボーナス！ やったね", "おやつだ！ もぐもぐ、おいしいね"]
    L += ["あれれ？ たまごが うごいてる", "あれ？ ひかってるよ", "わあ、ぴかぴか ひかってる！"]
    for name, rare in SPECIES:
        L.append(f"うまれた！ {'めずらしい、' if rare else ''}{name}の あかちゃんだよ")
        L.append(f"{name}が おおきく なったよ")
        L.append(f"{name}が おとなに なったよ！ すごい！")
        L.append(f"ゴール！ {name}が なかまに なったよ。 ずかんに はいったよ")
    L += ["あたらしい たまごが とどいたよ", "もういちど おすと、ひとつ もどるよ", "こえを だすよ"]
    L += [f"{n}の ばんだよ" for n in CHILDREN]
    return L

if __name__ == "__main__":
    for l in lines(): print(l)
